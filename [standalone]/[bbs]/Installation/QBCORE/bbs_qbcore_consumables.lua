local function mergeConsumables(targetTable, sourceTable)
    for itemName, value in pairs(sourceTable) do
        targetTable[itemName] = value
    end
end

local function countEntries(sourceTable)
    local total = 0
    for _ in pairs(sourceTable) do
        total = total + 1
    end
    return total
end

mergeConsumables(Config.Consumables.eat, bbsConsumables.eat)
mergeConsumables(Config.Consumables.drink, bbsConsumables.drink)
mergeConsumables(Config.Consumables.alcohol, bbsConsumables.alcohol)

if not IsDuplicityVersion() then return end

local function registerConsumable(itemName, clientEvent)
    QBCore.Functions.CreateUseableItem(itemName, function(source, item)
        local Player = QBCore.Functions.GetPlayer(source)
        if not Player or not item then return end
        if not Player.Functions.GetItemByName(item.name) then return end

        TriggerClientEvent(clientEvent, source, item.name)
    end)
end

for itemName in pairs(bbsConsumables.eat) do
    registerConsumable(itemName, 'consumables:client:Eat')
end

for itemName in pairs(bbsConsumables.drink) do
    registerConsumable(itemName, 'consumables:client:Drink')
end

for itemName in pairs(bbsConsumables.alcohol) do
    registerConsumable(itemName, 'consumables:client:DrinkAlcohol')
end

print(('[BBS Consumables] Loaded %s eat, %s drink, %s alcohol items.'):format(
    countEntries(bbsConsumables.eat),
    countEntries(bbsConsumables.drink),
    countEntries(bbsConsumables.alcohol)
))
