function QuickSwapDrivebyStyle()
  if ENDA_VehicleState.id == 0 then
    return
  end
  local groupIndex = ENDA_WeaponClipsetState.groupIndex
  if ENDA_WeaponClipsetState.style[groupIndex] == ENDA_WeaponClipsetState.laststyle[groupIndex] then
    return
  end
  if ENDA_WeaponClipsetState.dict == "NONE" then
    return
  end
  local previousStyle = ENDA_WeaponClipsetState.laststyle[groupIndex]
  ENDA_WeaponClipsetState.laststyle[groupIndex] = ENDA_WeaponClipsetState.style[groupIndex]
  ENDA_WeaponClipsetState.style[groupIndex] = previousStyle
  if previousStyle == "DEFAULT" then
    if ENDA_LocaleStrings ~= nil and ENDA_LocaleStrings.qswapDefault ~= nil then
      DisplayNotification(ENDA_LocaleStrings.qswapDefault)
    else
      DisplayNotification("QuickSwap: Default")
    end
  else
    if ENDA_LocaleStrings ~= nil and ENDA_LocaleStrings.qswapCustom ~= nil then
      DisplayNotification(ENDA_LocaleStrings.qswapCustom)
    else
      DisplayNotification("QuickSwap: Custom")
    end
  end
  ApplyDrivebyClipset()
  UpdateAimCameraMode()
end

function RegisterQuickSwapCommand()
  if not CONFIG.allowQuickSwap then
    return
  end
  local commandName = "swapstyle"
  if CONFIG.quickSwapCommand ~= nil and CONFIG.quickSwapCommand ~= false and CONFIG.quickSwapCommand ~= "none" then
    commandName = CONFIG.quickSwapCommand
  end
  RegisterCommand(commandName, QuickSwapDrivebyStyle, false)
  if CONFIG.quickSwapKeybind ~= nil and CONFIG.quickSwapKeybind ~= "none" then
    RegisterKeyMapping(commandName, "Aimstyle Quick Swap", "keyboard", CONFIG.quickSwapKeybind)
  end
  if CONFIG.quickSwapCommand == nil or CONFIG.quickSwapCommand == false or CONFIG.quickSwapCommand == "none" then
    TriggerEvent("chat:removeSuggestion", "/" .. commandName)
  end
end

function UpdateAimSwayAmplitude(vehicleSpeed)
  ENDA_CameraState.targetAmp = CONFIG.baseAimSwayValue + 0.1 * math.floor(vehicleSpeed / 4.5)
  if ENDA_CameraState.currentAmp ~= ENDA_CameraState.targetAmp then
    ENDA_CameraState.currentAmp = ENDA_CameraState.targetAmp
    if ENDA_CameraState.active == "GTA" then
      SetGameplayCamShakeAmplitude(ENDA_CameraState.currentAmp)
    elseif ENDA_CameraState.active == "FPV_AIM" then
      SetCamShakeAmplitude(ENDA_CameraState.view.FPV_AIM, ENDA_CameraState.currentAmp * 2)
    end
  end
end

