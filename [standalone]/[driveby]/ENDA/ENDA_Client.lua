function SpawnDevSeatPeds()
    if not DoesEntityExist(ENDA_DevVehicle.id) then
        return
    end

    for seatIndex = -1, ENDA_DevVehicle.seats, 1 do
        local seatKey = tostring(seatIndex)

        if ENDA_DevSeatPeds[seatKey] == nil then
            local seatPed = {
                ent = ClonePed(ENDA_PlayerState.id, true, true, false),
                x = 8,
                y = 8,
                z = 3,
                anim = {},
            }
            ENDA_DevSeatPeds[seatKey] = seatPed

            if not DoesEntityExist(seatPed.ent) then
                Wait(50)
            end

            FreezeEntityPosition(seatPed.ent, true)
            SetEntityNoCollisionEntity(ENDA_DevVehicle.id, seatPed.ent, false)
            SetEntityAlpha(seatPed.ent, 150)
            SetPedKeepTask(seatPed.ent, true)

            local pistolHash = 453432689
            RequestWeaponAsset(pistolHash, 31, 0)
            GiveWeaponToPed(seatPed.ent, pistolHash, 12, false, true)
            Wait(15)
            SetCurrentPedWeapon(seatPed.ent, pistolHash, true)
            Wait(15)

            if seatKey == "0" then
                seatPed.hand = 0
                SetDevSeatHandedness(seatKey, 1)
            end

            if seatKey == "2" then
                SetDevSeatHandedness(seatKey, 1)
            end

            seatPed.anim = { GetDevAnimDictForSeat(seatKey), 0.49 }
            RequestAnimDict(seatPed.anim[1])
            RepositionDevSeatPed(seatKey)
            Wait(50)
        end
    end
end

function UpdateDevSeatAnimTimes()
    if ENDA_DevVehicle.id == 0 then
        return
    end

    ENDA_DevMouse.pressed = false

    for seatIndex = -1, ENDA_DevVehicle.seats, 1 do
        ENDA_DevSeatKey = tostring(seatIndex)
        local seatPed = ENDA_DevSeatPeds[ENDA_DevSeatKey]

        if seatPed ~= nil and seatPed.ent ~= nil and seatPed.anim ~= nil then
            SetEntityAnimCurrentTime(seatPed.ent, seatPed.anim[1], "sweep_med", seatPed.anim[2])
        end

        if seatPed ~= nil and seatPed.hidden ~= nil then
            ENDA_DevMouse.pressed = true
        end

        if not ENDA_DevHidePlayer then
            local controlId = ENDA_DevSeatControlIds[seatIndex + 2]
            if IsDisabledControlJustPressed(0, controlId) then
                if ENDA_DevSelectedSeat ~= ENDA_DevSeatKey then
                    if ENDA_DevSelectedSeat ~= nil then
                        local previousSeat = ENDA_DevSeatPeds[ENDA_DevSelectedSeat]
                        if previousSeat ~= nil and previousSeat.hidden == nil then
                            SetEntityAlpha(previousSeat.ent, 150)
                        end
                    end

                    local selectedSeat = ENDA_DevSeatPeds[ENDA_DevSeatKey]
                    if selectedSeat ~= nil then
                        ENDA_DevSelectedSeat = ENDA_DevSeatKey

                        local lookTarget = selectedSeat.seatPos + vector3(
                            ENDA_DevOffsetXSteps[selectedSeat.x],
                            ENDA_DevOffsetXSteps[selectedSeat.y],
                            ENDA_DevOffsetZSteps[selectedSeat.z] + 0.75
                        )
                        PointCamAtCoord(ENDA_DevFreecam.id, lookTarget)

                        if selectedSeat.hidden == nil then
                            SetEntityAlpha(selectedSeat.ent, 255)
                        end
                    else
                        ENDA_DevSelectedSeat = nil
                    end
                end
            end
        end
    end

    if ENDA_DevMouse.pressed then
        DrawDevText(0.12, 0.91, "Hidden peds will NOT be printed", 0.3, nil, 150)
    end
end

function SpawnDevVehicle(modelHash)
    if modelHash == nil then
        modelHash = 736902334
    end

    local waitAttempts = 0
    RequestModel(modelHash)

    if ENDA_DevVehicle.id ~= 0 then
        SetEntityAsMissionEntity(ENDA_DevVehicle.id, true)
        DeleteEntity(ENDA_DevVehicle.id)
    end

    while not HasModelLoaded(modelHash) do
        Wait(50)
        waitAttempts = waitAttempts + 1
        if waitAttempts > 60 then
            DisplayNotification("Loading Vehicle Timed Out")
            break
        end
    end

    if not HasModelLoaded(modelHash) then
        return
    end

    waitAttempts = 0
    ENDA_DevVehicle.id = CreateVehicle(modelHash, ENDA_DevSpawnPosition, 0.0, false, false)

    while not DoesEntityExist(ENDA_DevVehicle.id) do
        Wait(50)
        waitAttempts = waitAttempts + 1
        if waitAttempts > 60 then
            DisplayNotification("Spawning Vehicle Timed Out")
            break
        end
    end

    if not DoesEntityExist(ENDA_DevVehicle.id) then
        return
    end

    ENDA_DevVehicle.seats = GetVehicleModelNumberOfSeats(modelHash) - 2
    if ENDA_DevVehicle.seats > 6 then
        ENDA_DevVehicle.seats = 6
    end

    SetModelAsNoLongerNeeded(modelHash)
    FreezeEntityPosition(ENDA_DevVehicle.id, true)
    SetEntityCollision(ENDA_DevVehicle.id, false, false)
    RollDownWindows(ENDA_DevVehicle.id)
    RefreshAllDevSeatPeds()
end

function OpenDevVehicleModelKeyboard()
    if ENDA_DevHidePlayer then
        return
    end

    ENDA_DevHidePlayer = true
    DisplayOnscreenKeyboard(1, "dev_vehicle_select", "Enter vehicle model name", "", "", "", "", 64)

    local keyboardStatus = UpdateOnscreenKeyboard()
    Citizen.CreateThread(function()
        while keyboardStatus == 0 do
            keyboardStatus = UpdateOnscreenKeyboard()
            DisableAllControlActions(0)
            Wait(0)
        end

        if keyboardStatus == 1 then
            local modelName = GetOnscreenKeyboardResult()
            if string.len(modelName) > 0 then
                ENDA_DevDefaultVehicle = modelName
                local modelHash = GetHashKey(modelName)

                if ENDA_BuiltinVehicleLayouts[modelHash] == nil then
                    SpawnDevVehicle(modelHash)
                    ENDA_DevHidePlayer = false
                else
                    DisplayNotification("Vehicle is already configured")
                    ENDA_DevHidePlayer = false
                    OpenDevVehicleModelKeyboard()
                end
            else
                DisplayNotification("No valid text entered")
                ENDA_DevHidePlayer = false
            end
        else
            ENDA_DevHidePlayer = false
        end
    end)
end

