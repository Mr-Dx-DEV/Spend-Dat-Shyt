function SnapDevOffsetToGrid(seatIndex, snappedCoords)
    for stepIndex = 1, #ENDA_DevOffsetXSteps do
        if snappedCoords.x == ENDA_DevOffsetXSteps[stepIndex] then
            ENDA_DevSeatPeds[seatIndex].x = stepIndex
        end
        if snappedCoords.y == ENDA_DevOffsetXSteps[stepIndex] then
            ENDA_DevSeatPeds[seatIndex].y = stepIndex
        end
    end

    for stepIndex = 1, #ENDA_DevOffsetZSteps do
        if snappedCoords.z == ENDA_DevOffsetZSteps[stepIndex] then
            ENDA_DevSeatPeds[seatIndex].z = stepIndex
        end
    end

    RepositionDevSeatPed(seatIndex)
end

function GetDevSeatWorldOffset(seatKey)
