function SyncFpvLookYawFromOffset()
    ENDA_CameraState.relYaw = Clamp(
        NormalizeAngle(ENDA_LookState.lookOffset.z - ENDA_CameraState.rot.z),
        -160.0,
        160.0
    )
    ENDA_CameraState.yaw = NormalizeAngle(ENDA_CameraState.rot.z + ENDA_CameraState.relYaw)
    ENDA_LookState.lookOffset = vector3(
        ENDA_LookState.lookOffset.x,
        ENDA_LookState.lookOffset.y,
        ENDA_CameraState.yaw
    )
    ENDA_CameraState.rot = ENDA_LookState.lookOffset
end

function ComputeTpvTargetOffset()
    local clipsetPose = ENDA_ClipsetDictTemplate[4]
    if clipsetPose == "v8k" or clipsetPose == "p7l" then
        return ENDA_TpvOffsetState.OFFSET.LEFT[ENDA_TpvOffsetState.zoom]
    end

    local seat = ENDA_VehicleState.seat.current
    if seat == 2 then
        return ENDA_TpvOffsetState.OFFSET.LEFT[ENDA_TpvOffsetState.zoom]
    end

    if seat ~= 0 then
        return ENDA_TpvOffsetState.OFFSET.RIGHT[ENDA_TpvOffsetState.zoom]
    end

    local layout = ENDA_VehicleState.layout
    if layout == nil then
        if ENDA_VehicleState.class == 8 then
            return ENDA_TpvOffsetState.OFFSET.RIGHT[ENDA_TpvOffsetState.zoom]
        elseif CONFIG.defaultHandForFrontPassenger == 0 then
            return ENDA_TpvOffsetState.OFFSET.LEFT[ENDA_TpvOffsetState.zoom]
        elseif CONFIG.defaultHandForFrontPassenger == 1 then
            return ENDA_TpvOffsetState.OFFSET.RIGHT[ENDA_TpvOffsetState.zoom]
        end
        return nil
    end

    if layout.hand == nil or layout.hand == 0 then
        return ENDA_TpvOffsetState.OFFSET.LEFT[ENDA_TpvOffsetState.zoom]
    end

    return nil
end

function UpdateFpvCamLerp(applyEase, refreshTimeNow)
    if not ENDA_FpvCamLerp.start then
        return
    end

    if ENDA_FpvCamLerp.progress >= 1.0 then
        return
    end

    if refreshTimeNow then
        ENDA_LookState.timeNow = GetGameTimer()
    end

    local progress = math.min((ENDA_LookState.timeNow - ENDA_FpvCamLerp.start) / ENDA_FpvCamLerp.duration, 1.0)
    ENDA_FpvCamLerp.pCalc = progress

    if applyEase then
        local alpha = ENDA_FpvCamLerp.pCalc
        if alpha < 0.5 then
            ENDA_FpvCamLerp.pCalc = 2 * alpha * alpha
        else
            ENDA_FpvCamLerp.pCalc = -1 + (4 - 2 * alpha) * alpha
        end
    end

    ENDA_FpvCamLerp.rot = vector3(
        LerpAngle(ENDA_CameraState.lastrot.x, ENDA_CameraState.rot.x, ENDA_FpvCamLerp.pCalc),
        LerpAngle(ENDA_CameraState.lastrot.y, ENDA_CameraState.rot.y, ENDA_FpvCamLerp.pCalc),
        LerpAngle(ENDA_CameraState.lastrot.z, ENDA_CameraState.rot.z, ENDA_FpvCamLerp.pCalc)
    )
    ENDA_FpvCamLerp.progress = ENDA_FpvCamLerp.pCalc
    ENDA_FpvCamLerp.distance = #(ENDA_CameraState.rot - ENDA_FpvCamLerp.rot)

    if ENDA_FpvCamLerp.distance > 1.0 then
        ENDA_LookState.lookOffset = ENDA_CameraState.rot
        ENDA_CameraState.rot = ENDA_FpvCamLerp.rot
        ENDA_CameraState.relYaw = Clamp(
            NormalizeAngle(ENDA_CameraState.lastrot.z - ENDA_LookState.lookOffset.z),
            -160,
            160
        )
    else
        ENDA_FpvCamLerp.start = nil
        ENDA_FpvCamLerp.progress = 0
    end
end

