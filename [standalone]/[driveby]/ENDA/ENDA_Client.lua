function RemovePlayerFromClipsetTracker(playerId)
    for clipsetName, playerList in pairs(ENDA_ClipsetUsageTracker) do
        for index = 1, #playerList do
            if playerList[index] == playerId then
                table.remove(playerList, index)
                if #playerList == 0 then
                    ENDA_ClipsetUsageTracker[clipsetName] = nil
                    RemoveClipSet(clipsetName)
                end
                break
            end
        end
    end
end

