function DrivebyHandleNotInVehicle()
  ENDA_VehicleState.enterId = GetVehiclePedIsTryingToEnter(ENDA_PlayerState.id)
  ENDA_VehicleState.id = GetVehiclePedIsIn(ENDA_PlayerState.id, false)

  if ENDA_VehicleState.enterId ~= 0 then
    if not ENDA_Flag20 then
      ENDA_AntiShuffleState.seat = GetSeatPedIsTryingToEnter(ENDA_PlayerState.id)
      if ENDA_AntiShuffleState.seat == -1 then
        NetworkRequestControlOfEntity(ENDA_VehicleState.enterId)
      end
      ENDA_Flag20 = true
      SetPlayerCanDoDriveBy(PlayerId(), false)
    end
  elseif ENDA_Flag20 then
    if ENDA_VehicleState.enterId == 0 and ENDA_VehicleState.id == 0 then
      ENDA_AntiShuffleState.seat = nil
      ENDA_Flag20 = false
      if ENDA_AntiShuffleState.ped ~= 0 then
        DeleteAntiShufflePed()
      end
    elseif ENDA_Flag20 and ENDA_VehicleState.id ~= 0 then
      ENDA_AntiShuffleState.seat = nil
      ENDA_Flag20 = false
      OnVehicleEntered(true)
      Citizen.Wait(500)
    elseif ENDA_VehicleState.id ~= 0 then
      ENDA_AntiShuffleState.seat = nil
      ENDA_Flag20 = false
      OnVehicleEntered(true)
      Citizen.Wait(500)
    elseif ENDA_Flag20 and ENDA_VehicleState.id == 0 then
      UpdateAntiShuffleVehicleEnter()
    end
  end
end

function DrivebyHandleInVehicle()
  if ENDA_VehicleState.id == 0 then
    return
  end
  ENDA_VehicleState.id = GetVehiclePedIsIn(ENDA_PlayerState.id, false)
  if ENDA_VehicleState.id == 0 then
    ENDA_AntiShuffleState.bones = { nil, nil, 0.0 }
    ENDA_VehicleState.id = 0
    ENDA_VehicleState.lastmodel = ENDA_VehicleState.model
    ENDA_VehicleState.model = nil
    ENDA_VehicleState.seat.last = ENDA_VehicleState.seat.current
    ENDA_VehicleState.seat.current = nil
    TriggerEvent("ENDA:ExitedVehicle")
    Citizen.Wait(500)
  elseif ENDA_VehicleState.id ~= ENDA_VehicleState.lastId then
    OnVehicleEntered(true)
    Citizen.Wait(500)
  end
end

