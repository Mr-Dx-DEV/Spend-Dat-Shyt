function UpdateDrivebyAimingStyle(weaponGroupIndex, styleName)
  if styleName == nil then
    styleName = "DEFAULT"
  end
  local groupIndex = tonumber(weaponGroupIndex)
  if styleName == "DEFAULT" then
    SetDrivebyStyle(groupIndex, "DEFAULT")
  else
    local validationCode = ValidateDrivebyStyle(groupIndex, styleName)
    if validationCode == 747 then
      SetDrivebyStyle(groupIndex, styleName)
    elseif validationCode == 420 then
      if GetResourceState("ENDA_01") == "started" then
        print("ENDA-ERROR: 420 (Invalid driveby style, try restarting animation resource)")
      else
        TriggerServerEvent("ENDA:ErrorLog", 404, styleName)
        print("ENDA-ERROR: 404 (Required resource not started, check the animation resource)")
      end
    elseif validationCode == 666 then
      TriggerServerEvent("ENDA:ErrorLog", 466, styleName)
      print("ENDA-ERROR: 466 (Driveby style )")
    end
  end
end
