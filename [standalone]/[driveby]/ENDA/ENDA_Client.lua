if CONFIG.useIntegratedAntiShuffle then
    function ShuffleSeat(seatIndexArg)
        if ENDA_VehicleState.id == 0 then
            return
        end

        if ENDA_AntiShuffleState.moving then
            return
        end

        local vehicleId = ENDA_VehicleState.id
        local currentSeat = ENDA_VehicleState.seat.current

        if seatIndexArg ~= nil then
            local targetSeat = tonumber(seatIndexArg)

            if targetSeat == -1 then
                if not CanTakeDriverSeat() then
                    return
                end

                DeleteAntiShufflePed()
                PrepareAntiShuffleMove()

                if currentSeat == 0 then
                    ShuffleToAdjacentSeat(2000)
                else
                    EnterVehicleForShuffle(-1)
                    ScheduleAntiShuffleMoveComplete(500, false)
                end
                return
            end

            if not IsVehicleSeatFree(vehicleId, targetSeat, true) then
                return
            end

            PrepareAntiShuffleMove()
            EnterVehicleForShuffle(targetSeat)

            if targetSeat == 0 then
                if currentSeat == -1 and ENDA_VehicleState.class ~= 8 then
                    ShuffleToAdjacentSeat(2000)
                else
                    EnterVehicleForShuffle(0)
                    ScheduleAntiShuffleMoveComplete(500, true)
                end
            elseif (targetSeat == 1 and currentSeat == 2) or (targetSeat == 2 and currentSeat == 1) then
                ShuffleToAdjacentSeat(2000)
            else
                ScheduleAntiShuffleMoveComplete(500, false)
            end
            return
        end

        if currentSeat == -1 then
            if not IsVehicleSeatFree(vehicleId, 0, true) then
                return
            end

            PrepareAntiShuffleMove()

            if ENDA_VehicleState.class == 8 then
                EnterVehicleForShuffle(0)
                ScheduleAntiShuffleMoveComplete(500, true)
            else
                TaskShuffleToNextVehicleSeat(ENDA_PlayerState.id, vehicleId)
                ScheduleAntiShuffleMoveComplete(2000, true)
            end
            return
        end

        if currentSeat == 0 then
            if not CanTakeDriverSeat() then
                return
            end

            DeleteAntiShufflePed()
            PrepareAntiShuffleMove()
            TaskShuffleToNextVehicleSeat(ENDA_PlayerState.id, vehicleId)

            if ENDA_VehicleState.class == 8 then
                ScheduleAntiShuffleMoveComplete(1000, false)
            else
                ScheduleAntiShuffleMoveComplete(2000, false)
            end
            return
        end

        local pairedSeatByCurrentSeat = {
            [1] = 2,
            [2] = 1,
            [3] = 4,
            [4] = 3,
            [5] = 6,
            [6] = 5,
        }

        local pairedSeat = pairedSeatByCurrentSeat[currentSeat]
        if pairedSeat == nil then
            return
        end

        if not IsVehicleSeatFree(vehicleId, pairedSeat, true) then
            return
        end

        PrepareAntiShuffleMove()

        if currentSeat == 1 or currentSeat == 2 then
            ShuffleToAdjacentSeat(2000)
        else
            EnterVehicleForShuffle(pairedSeat)
            ScheduleAntiShuffleMoveComplete(500, false)
        end
    end

    exports("shuffle", ShuffleSeat)

    if CONFIG.allowShuffleCommand ~= "none" then
        RegisterCommand(CONFIG.allowShuffleCommand, function(source, args)
            if CONFIG.allowShuffleSpecific and args[1] ~= nil then
                ShuffleSeat(args[1])
            else
                ShuffleSeat()
            end
        end)

        if CONFIG.allowShuffleKeybind ~= "none" then
            RegisterKeyMapping(CONFIG.allowShuffleCommand, "Seat Shuffle", "keyboard", CONFIG.allowShuffleKeybind)
            TriggerEvent("chat:removeSuggestion", "/" .. CONFIG.allowShuffleCommand)
        end
    end

    AddEventHandler("onResourceStop", function()
        if ENDA_AntiShuffleState and ENDA_AntiShuffleState.moving then
            ENDA_AntiShuffleState.moving = false
            DeleteAntiShufflePed()
        end
    end)
end

function UpdateAntiShuffleVehicleEnter()
    ENDA_AntiShuffleState.veh = GetVehiclePedIsTryingToEnter(ENDA_PlayerState.id)

    if ENDA_AntiShuffleState.veh ~= 0 then
        if ENDA_AntiShuffleState.ped == 0 then
            ENDA_AntiShuffleState.seat = GetSeatPedIsTryingToEnter(ENDA_PlayerState.id)

            if ENDA_AntiShuffleState.seat == -1
                and IsVehicleSeatFree(ENDA_AntiShuffleState.veh, -1)
                and IsVehicleSeatFree(ENDA_AntiShuffleState.veh, 0) then

                NetworkRequestControlOfEntity(ENDA_AntiShuffleState.veh)

                if ENDA_AntiShuffleState.bones[2] == nil then
                    ENDA_AntiShuffleState.bones[1] = GetEntityBoneIndexByName(ENDA_AntiShuffleState.veh, "seat_dside_f")
                    ENDA_AntiShuffleState.bones[2] = GetEntityBoneIndexByName(ENDA_AntiShuffleState.veh, "seat_pside_f")
                end

                local passengerBoneIndex = ENDA_AntiShuffleState.bones[2]
                if passengerBoneIndex ~= nil and passengerBoneIndex ~= -1 then
                    ENDA_PlayerState.coord = GetEntityCoords(ENDA_PlayerState.id, true)

                    local distanceToPassengerSeat = #(
                        GetWorldPositionOfEntityBone(ENDA_AntiShuffleState.veh, passengerBoneIndex)
                        - ENDA_PlayerState.coord
                    )
                    ENDA_AntiShuffleState.bones[3] = distanceToPassengerSeat

                    if distanceToPassengerSeat < 1.5 then
                        local distanceToDriverSeat = #(
                            GetWorldPositionOfEntityBone(ENDA_AntiShuffleState.veh, ENDA_AntiShuffleState.bones[1])
                            - ENDA_PlayerState.coord
                        )

                        if distanceToPassengerSeat < distanceToDriverSeat then
                            SpawnAntiShufflePed(ENDA_AntiShuffleState.veh)
                            Citizen.Wait(500)
                        end
                    end
                end
            end
        end
    elseif ENDA_VehicleState.id == 0
        and ENDA_AntiShuffleState.veh == 0
        and ENDA_AntiShuffleState.ped ~= 0 then
        DeleteAntiShufflePed()
    end
end

