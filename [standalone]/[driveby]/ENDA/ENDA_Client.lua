                            ENDA_CameraState.relYaw = -160
                            AttachCamToPedBone(
                                ENDA_CameraState.view.FPV_VEH,
                                ENDA_PlayerState.id,
                                31086,
                                0.35,
                                0.05,
                                0.075,
                                true
                            )
                            ENDA_CameraState.moved = true
                        end
                    end
                end
                ClampGameplayCamYaw(ENDA_CameraState.rear - 5.0, ENDA_CameraState.rear + 5.0)
            elseif ENDA_CameraState.rear ~= 0 then
                if ENDA_PlayerState.aiming and ENDA_WeaponClipsetState.dict == "GTA" then
                    ENDA_MouseInput.lastmove = ENDA_LookState.timeNow
                    ENDA_LookState.isLooking = true
                    ENDA_LookState.lookOffset = GetGameplayCamRot(0)
                else
                    ENDA_CameraState.relYaw = 0
                end
                ENDA_CameraState.rear = 0
            end

            if ENDA_CameraState.rear ~= 0 then
                ENDA_LookState.lookOffset = ENDA_CameraState.rot
                ENDA_CameraState.rot = vector3(
                    ENDA_CameraState.rot.x,
                    ENDA_CameraState.rot.y,
                    NormalizeAngle(ENDA_CameraState.rot.z + ENDA_CameraState.rear)
                )
            elseif ENDA_MouseInput.moved then
                if not IsNuiFocused() then
                    if ENDA_LookState.lookOffset == vector3(0, 0, 0) then
                        ENDA_LookState.lookOffset = ENDA_CameraState.rot
                    else
                        ENDA_MouseInput.lastmove = ENDA_LookState.timeNow
                        ENDA_LookState.isLooking = true

                        if ENDA_InitialFlag then
                            local mouseDelta = vector3(
                                (ENDA_MouseInput.Y - ENDA_MouseInput.lastY) * CONFIG.fpLookSensitivity[2],
                                0.0,
                                (ENDA_MouseInput.X - ENDA_MouseInput.lastX) * CONFIG.fpLookSensitivity[1]
                            )
                            ENDA_LookState.lookOffset = ENDA_LookState.lookOffset - mouseDelta
                        else
                            local mouseDelta = vector3(
                                ENDA_MouseInput.Y * 1.0,
                                0.0,
                                ENDA_MouseInput.X * 2.0
                            )
                            ENDA_LookState.lookOffset = ENDA_LookState.lookOffset - mouseDelta
                        end

                        ENDA_CameraState.relYaw = Clamp(
                            NormalizeAngle(ENDA_LookState.lookOffset.z - ENDA_CameraState.rot.z),
                            -160.0,
                            160.0
                        )
                        ENDA_CameraState.yaw = NormalizeAngle(ENDA_CameraState.rot.z + ENDA_CameraState.relYaw)
                        ENDA_CameraState.pitch = NormalizeAngle(
                            ENDA_CameraState.rot.x + Clamp(
                                ENDA_LookState.lookOffset.x - ENDA_CameraState.rot.x,
                                -35.0,
                                35.0
                            )
                        )
                        ENDA_LookState.lookOffset = vector3(
                            ENDA_CameraState.pitch,
                            ENDA_CameraState.rot.y,
                            ENDA_CameraState.yaw
                        )
                        ENDA_CameraState.rot = ENDA_LookState.lookOffset
                    end
                end
            else
                local resetMode = CONFIG.resetLookWhileDriving

                if resetMode == 2 then
                    if ENDA_LookState.isLooking then
                        if ENDA_LookState.timeNow - ENDA_MouseInput.lastmove > CONFIG.resetLookDelay
                            and ENDA_VehicleState.speed > 5.0
                            and not ENDA_PlayerState.aiming then
                            ENDA_FpvCamLerp.start = ENDA_LookState.timeNow
                            ENDA_FpvCamLerp.progress = 0
                            ENDA_FpvCamLerp.rot = nil
                            ENDA_FpvCamLerp.distance = 0.0
                            ENDA_LookState.isLooking = false
                            ENDA_CameraState.lastrot = ENDA_LookState.lookOffset
                            ENDA_LookState.lookOffset = ENDA_CameraState.rot
                        end
                    elseif ENDA_FpvCamLerp.start == nil then
                        ENDA_LookState.lookOffset = ENDA_CameraState.rot
                    end
                elseif ENDA_LookState.isLooking then
                    SyncFpvLookYawFromOffset()
                elseif ENDA_FpvCamLerp.start == nil then
                    ENDA_LookState.lookOffset = ENDA_CameraState.rot
                end
            end
        elseif ENDA_LookState.isLooking then
            SyncFpvLookYawFromOffset()
        end

        if ENDA_InitialFlag then
            if ENDA_MouseInput.X < 0.1 then
                ENDA_MouseInput.X = 0.2
                SetCursorLocation(0.2, ENDA_MouseInput.Y)
            elseif ENDA_MouseInput.X > 0.9 then
                ENDA_MouseInput.X = 0.8
                SetCursorLocation(0.8, ENDA_MouseInput.Y)
            end

            if ENDA_MouseInput.Y < 0.1 then
                ENDA_MouseInput.Y = 0.2
                SetCursorLocation(ENDA_MouseInput.X, 0.2)
            elseif ENDA_MouseInput.Y > 0.9 then
                ENDA_MouseInput.Y = 0.8
                SetCursorLocation(ENDA_MouseInput.X, 0.8)
            end

            ENDA_MouseInput.lastX = ENDA_MouseInput.X
            ENDA_MouseInput.lastY = ENDA_MouseInput.Y
        end

        UpdateFpvVehicleCamAttach()
        ResetFpvLookState()
        SetCamRot(ENDA_CameraState.view.FPV_VEH, ENDA_CameraState.rot, 0)
        ENDA_CameraState.lastrot = ENDA_CameraState.rot

        if ENDA_PlayerState.aiming then
            if ENDA_WeaponClipsetState.dict ~= "GTA" then
                if ENDA_CameraState.moved then
                    AttachCamToPedBone(
                        ENDA_CameraState.view.FPV_VEH,
                        ENDA_PlayerState.id,
                        31086,
                        0.0,
                        0.05,
                        0.075,
                        true
                    )
                    ENDA_CameraState.moved = false
                end
                ENDA_CameraState.relYaw = 0
                SetCamRot(ENDA_CameraState.view.FPV_AIM, ENDA_CameraState.lastrot, 0)
                SetCamActive(ENDA_CameraState.view.FPV_VEH, false)
                SetCamActive(ENDA_CameraState.view.FPV_AIM, true)
                ENDA_FpvCamLerp.start = GetGameTimer()
                ENDA_FpvCamLerp.progress = 0.01
                ENDA_CameraState.active = "FPV_AIM"
            end
        elseif ENDA_PlayerState.aiming then
            if ENDA_WeaponClipsetState.dict == "GTA" and ENDA_CameraState.rear == 0 then
                ClampGameplayCamYaw(-165.0, 165.0)
            end
        elseif not ENDA_LookState.isLooking and not ENDA_LookState.firstTime then
            ClampGameplayCamYaw(0.0, 0.0)
        end

        ClampGameplayCamPitch(0.0, 0.0)
    end
end

