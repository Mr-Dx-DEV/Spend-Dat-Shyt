function GetRelativeHeadingBucket()
  local camHeading = GetGameplayCamRot(0).z
  local vehicleHeading = GetEntityHeading(ENDA_VehicleState.id)
  local relativeHeading = NormalizeAngle(camHeading - vehicleHeading)
  ENDA_PlayerState.heading = relativeHeading
  if relativeHeading >= -45 and relativeHeading <= 45 then
    return "0"
  elseif relativeHeading > 45 then
    return "90l"
  elseif relativeHeading < -45 then
    return "90r"
  end
  return nil
end

function ClearPlayerDownedAnim()
  ENDA_PlayerState.downed = false
  StopAnimTask(ENDA_PlayerState.id, ENDA_WeaponClipsetState.dict, "down_" .. ENDA_PlayerState.downAnimHeading, 2.0)
end

function PlayerDowned(durationSeconds, mirrorRightRear)
  if ENDA_VehicleState.id == 0 then
    return
  end
  if ENDA_WeaponClipsetState.dict == "GTA" or ENDA_WeaponClipsetState.dict == "NONE" then
    return
  end
  if not ENDA_PlayerState.aiming and not IsControlPressed(0, 25) then
    return
  end

  local headingBucket = GetRelativeHeadingBucket()
  if GetVehicleHasFlag(ENDA_VehicleState.id, 64) then
    mirrorRightRear = true
  end
  if mirrorRightRear and headingBucket == "90r" then
    headingBucket = "0"
  end
  if headingBucket == nil then
    return
  end

  ENDA_PlayerState.downed = true
  ENDA_PlayerState.downAnimHeading = headingBucket
  local animName = "down_" .. headingBucket
  TaskPlayAnim(ENDA_PlayerState.id, ENDA_WeaponClipsetState.dict, animName, 4.0, 4.0, -1, 262146, 0.0, false, false, false)
  if durationSeconds ~= 0 and durationSeconds ~= -1 then
    Citizen.SetTimeout(durationSeconds * 1000, ClearPlayerDownedAnim)
  end
end
exports("PlayerDowned", PlayerDowned)

