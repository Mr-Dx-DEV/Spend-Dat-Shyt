end

function ExportVehicleLayoutToConsole()
    local seatKey = "-1"
    local seatCodes = {}
    local nearestCoords = {}
    local seatsFragment = "seats={'"

    for seatIndex = -1, ENDA_DevVehicle.seats, 1 do
        seatKey = tostring(seatIndex)
        local seatPed = ENDA_DevSeatPeds[seatKey]

        if seatPed ~= nil then
            if seatPed.hidden == nil then
                if seatPed.x == 8 then
                    if seatPed.y == 8 then
                        if seatPed.z == 3 then
                            seatCodes[seatKey] = "DEFAULT"
                        end
                    end
                elseif seatKey == "-1" then
                    BuildOffsetPresetTable("DRIVER")
                    local offsetX, offsetY, offsetZ = GetDevSeatWorldOffset(seatKey)
                    local presetCode
                    presetCode, nearestCoords = FindNearestOffsetPreset("DRIVER", offsetX, offsetY, offsetZ)
                    seatCodes[seatKey] = presetCode
                    SnapDevOffsetToGrid(seatKey, nearestCoords)
                    ENDA_DevOffsetPresets.DRIVER = nil
                elseif seatKey == "0" then
                    if seatPed.hand ~= nil then
                        if seatPed.hand == 1 then
                            BuildOffsetPresetTable("PASS_R")
                            local offsetX, offsetY, offsetZ = GetDevSeatWorldOffset(seatKey)
                            local presetCode
                            presetCode, nearestCoords = FindNearestOffsetPreset("PASS_R", offsetX, offsetY, offsetZ)
                            seatCodes[seatKey] = presetCode
                            SnapDevOffsetToGrid(seatKey, nearestCoords)
                            ENDA_DevOffsetPresets.PASS_R = nil
                        end
                    else
                        BuildOffsetPresetTable("PASS_L")
                        local offsetX, offsetY, offsetZ = GetDevSeatWorldOffset(seatKey)
                        local presetCode
                        presetCode, nearestCoords = FindNearestOffsetPreset("PASS_L", offsetX, offsetY, offsetZ)
                        seatCodes[seatKey] = presetCode
                        SnapDevOffsetToGrid(seatKey, nearestCoords)
                        ENDA_DevOffsetPresets.PASS_L = nil
                    end
                elseif seatKey == "1" or seatKey == "3" or seatKey == "5" then
                    BuildOffsetPresetTable("REAR_L")
                    local offsetX, offsetY, offsetZ = GetDevSeatWorldOffset(seatKey)
                    local presetCode
                    presetCode, nearestCoords = FindNearestOffsetPreset("REAR_L", offsetX, offsetY, offsetZ)
                    seatCodes[seatKey] = presetCode
                    SnapDevOffsetToGrid(seatKey, nearestCoords)
                    ENDA_DevOffsetPresets.REAR_L = nil
                elseif seatKey == "2" or seatKey == "4" or seatKey == "6" then
                    BuildOffsetPresetTable("REAR_R")
                    local offsetX, offsetY, offsetZ = GetDevSeatWorldOffset(seatKey)
                    local presetCode
                    presetCode, nearestCoords = FindNearestOffsetPreset("REAR_R", offsetX, offsetY, offsetZ)
                    seatCodes[seatKey] = presetCode
                    SnapDevOffsetToGrid(seatKey, nearestCoords)
                    ENDA_DevOffsetPresets.REAR_R = nil
                end

                if seatKey ~= "-1" then
                    seatsFragment = seatsFragment .. "','"
                end
                seatsFragment = seatsFragment .. seatCodes[seatKey]
            end
        else
            if seatKey ~= "-1" then
                seatsFragment = seatsFragment .. "','"
            end
            seatsFragment = seatsFragment .. "NONE"
        end
    end

    local frontPassenger = ENDA_DevSeatPeds["0"]
    if frontPassenger.hand ~= nil and frontPassenger.hand == 1 then
        print("[`" .. ENDA_DevDefaultVehicle .. "`] = {" .. seatsFragment .. "'}, hand=1},")
    else
        print("[`" .. ENDA_DevDefaultVehicle .. "`] = {" .. seatsFragment .. "'}, hand=0},")
    end

    DisplayNotification("Printed to console (F8)")
end

