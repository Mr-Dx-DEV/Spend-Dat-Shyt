    return
  end
  if styleName == "DEFAULT" then
    RestoreVanillaOrDisableAiming()
    return
  end
  if not (seatClipCode == "NYD" and CONFIG.loadDefaultWhenClipsetNotFound) then
    seatClipCode = ENDA_ClipsetDictTemplate[6]
  end
  if seatClipCode == "DEFAULT" then
    ENDA_ClipsetDictTemplate[6] = "tsd"
  elseif seatClipCode == "GTA" then
    RestoreVanillaOrDisableAiming()
    return
  end
  local clipsetEntry = ENDA_CustomClipsetRegistry[weaponGroupIndex]
  if clipsetEntry then
    clipsetEntry = clipsetEntry[styleName]
  end
  if not clipsetEntry then
    RestoreVanillaOrDisableAiming()
    return
  end
  ENDA_ClipsetDictTemplate[2] = clipsetEntry.dict
  ENDA_ClipsetDictTemplate[4] = SeatIndexToPoseCode(ENDA_VehicleState.seat.current)
  ENDA_WeaponClipsetState.dict = table.concat(ENDA_ClipsetDictTemplate)
