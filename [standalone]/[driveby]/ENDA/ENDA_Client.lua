            elseif IsDisabledControlJustPressed(0, 117) then
                AdjustSelectedSeatAxis("z", -1, 1, 5, "numpad")
            end

            if IsDisabledControlPressed(0, 312) then
                ScrubSelectedSeatAnimTime(-1, IsDisabledControlPressed(0, 21))
            elseif IsDisabledControlPressed(0, 313) then
                ScrubSelectedSeatAnimTime(1, IsDisabledControlPressed(0, 21))
            end
        end
    end
end

function RunDevToolMainLoop()
    Citizen.CreateThread(function()
        DoScreenFadeOut(500)
        Citizen.Wait(500)
        EnterDevToolSession()
        Citizen.Wait(50)

        while ENDA_DevToolActive do
            Citizen.Wait(1)
            RenderDevToolUI()
            HandleDevCamMovement()
            UpdateDevSeatAnimTimes()
        end

        DoScreenFadeOut(500)
        Wait(500)
        ExitDevToolSession()
        Wait(250)
        DoScreenFadeIn(500)
    end)
end

RegisterCommand("edatool", function()
    if not ENDA_DevToolActive then
        ENDA_DevToolActive = true
        RunDevToolMainLoop()
    else
        ENDA_DevToolActive = false
    end
end)

AddEventHandler("onResourceStop", function()
    if ENDA_DevToolActive then
        ExitDevToolSession()
    end
end)

