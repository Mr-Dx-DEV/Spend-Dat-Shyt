                ENDA_MouseInput.moved = ENDA_MouseInput.X ~= 0.0 or ENDA_MouseInput.Y ~= 0.0
            end

            if IsControlPressed(0, 79) then
                if ENDA_CameraState.rear == 0 then
                    if ENDA_CameraState.relYaw > 45 then
