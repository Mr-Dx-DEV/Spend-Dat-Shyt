                        Wait(1)
                        if HasClipSetLoaded(value) then
                            break
                        end
                    end
                end
            end
            SetPedDriveByClipsetOverride(targetPed, value)
            table.insert(ENDA_ClipsetUsageTracker[value], serverId)
        end
    end
end)

function SplitString(text, separator)
    local parts = {}
    local pattern = "([^" .. separator .. "]+)"
    for segment in string.gmatch(text, pattern) do
        table.insert(parts, segment)
    end
    return parts
end
