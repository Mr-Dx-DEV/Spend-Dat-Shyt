function HandleDevCamMovement()
    if ENDA_DevFreecam.id == nil then
        return
    end
    if ENDA_DevHidePlayer then
        return
    end

    DisableControlAction(0, 1, true)
    DisableControlAction(0, 2, true)

    ENDA_DevFreecam.move = vector3(0.0, 0.0, 0.0)
    ENDA_DevFreecam.update = false

    if IsDisabledControlPressed(0, 21) then
        ENDA_DevFreecam.speed = 0.1
    else
        ENDA_DevFreecam.speed = 0.05
    end

    if IsDisabledControlPressed(0, 32) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(0.0, 0.0, ENDA_DevFreecam.speed)
        ENDA_DevFreecam.update = true
    elseif IsDisabledControlPressed(0, 33) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(0.0, 0.0, -ENDA_DevFreecam.speed)
        ENDA_DevFreecam.update = true
    end

    if IsDisabledControlPressed(0, 34) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(-ENDA_DevFreecam.speed, 0.0, 0.0)
        ENDA_DevFreecam.update = true
    elseif IsDisabledControlPressed(0, 35) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(ENDA_DevFreecam.speed, 0.0, 0.0)
        ENDA_DevFreecam.update = true
    end

    if IsDisabledControlPressed(0, 44) or IsDisabledControlPressed(0, 181) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(0.0, ENDA_DevFreecam.speed, 0.0)
        ENDA_DevFreecam.update = true
    elseif IsDisabledControlPressed(0, 38) or IsDisabledControlPressed(0, 180) then
        ENDA_DevFreecam.move = ENDA_DevFreecam.move + vector3(0.0, -ENDA_DevFreecam.speed, 0.0)
        ENDA_DevFreecam.update = true
    end

    if ENDA_DevFreecam.update then
        local rightVector, forwardVector, upVector, camPosition = GetCamMatrix(ENDA_DevFreecam.id)
        local moveDelta = camPosition
            + (forwardVector * ENDA_DevFreecam.move.y)
            + (rightVector * ENDA_DevFreecam.move.x)
            + (upVector * ENDA_DevFreecam.move.z)

        ENDA_DevFreecam.pos = moveDelta
        SetCamCoord(ENDA_DevFreecam.id, ENDA_DevFreecam.pos)
    end
end

