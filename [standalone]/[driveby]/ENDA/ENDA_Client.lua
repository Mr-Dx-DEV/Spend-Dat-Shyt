            ENDA_MouseInput.Y = GetDisabledControlNormal(0, 240)
        else
            ENDA_MouseInput.X = GetDisabledControlNormal(0, 1)
            ENDA_MouseInput.Y = GetDisabledControlNormal(0, 2)
        end

        if not ENDA_LookState.firstTime then
            if ENDA_InitialFlag then
                local deltaX = ENDA_MouseInput.X - ENDA_MouseInput.lastX
                local deltaY = ENDA_MouseInput.Y - ENDA_MouseInput.lastY
                ENDA_MouseInput.moved = math.sqrt(deltaX * deltaX + deltaY * deltaY) > ENDA_MouseInput.deadzone
