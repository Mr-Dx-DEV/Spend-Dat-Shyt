function RefreshAllDevSeatPeds()
    for seatIndex = -1, 6, 1 do
        local seatKey = tostring(seatIndex)
        local seatPed = ENDA_DevSeatPeds[seatKey]

        if seatPed ~= nil and seatPed.ent ~= nil then
            seatPed.x = 8
            seatPed.y = 8
