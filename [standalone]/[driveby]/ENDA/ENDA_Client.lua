function RequestClipSetWithRetry(clipSetName)
    RequestClipSet(clipSetName)

    local retryWaitMs = { 150, 250, 500, 500, 1000 }
    for _, waitMs in ipairs(retryWaitMs) do
        Citizen.Wait(waitMs)
