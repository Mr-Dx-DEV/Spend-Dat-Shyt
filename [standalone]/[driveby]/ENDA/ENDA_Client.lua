            ENDA_TpvOffsetState.offCur = LerpVector3(ENDA_TpvOffsetState.offCur, ENDA_TpvOffsetState.offTar, 0.1)
        else
            ENDA_TpvOffsetState.offCur = ENDA_TpvOffsetState.offTar
        end

