function Clamp(value, minValue, maxValue)
    return math.max(minValue, math.min(maxValue, value))
end

function NormalizeAngle(angle)
    angle = math.fmod(angle + 180.0, 360.0)
    if angle < 0 then
        angle = angle + 360.0
    end
    return angle - 180.0
end

function LerpAngle(fromAngle, toAngle, alpha)
    return fromAngle + NormalizeAngle(toAngle - fromAngle) * alpha
end
function VectorsNear(vecA, vecB, tolerance)
    tolerance = tolerance or 0.001
    return tolerance > math.abs(vecA[1] - vecB[1])
end

function LerpVector3(fromVec, toVec, alpha)
    return {
        fromVec[1] + (toVec[1] - fromVec[1]) * alpha,
        fromVec[2] + (toVec[2] - fromVec[2]) * alpha,
        fromVec[3] + (toVec[3] - fromVec[3]) * alpha,
    }
end

function RotateOffset(yawDegrees, offsetX, offsetY, offsetZ)
    local yawRad = math.rad(yawDegrees)
    local cosYaw = math.cos(yawRad)
    local sinYaw = math.sin(yawRad)
    return vector3(
        offsetX * cosYaw - offsetY * sinYaw,
        offsetX * sinYaw + offsetY * cosYaw,
        offsetZ
    )
end

