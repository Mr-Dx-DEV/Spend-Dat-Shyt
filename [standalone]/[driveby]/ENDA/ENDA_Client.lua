function OnVehicleEntered(skipFullSetup)
  if ENDA_VehicleState.id == 0 then
    return
  end
  Citizen.Wait(50)
  ENDA_PlayerState.player = PlayerId()
  ENDA_VehicleState.model = GetEntityModel(ENDA_VehicleState.id)
  ENDA_VehicleState.seat.current = GetPedVehicleSeatIndex(ENDA_PlayerState.id)

  local sameVehicleAndSeat = not skipFullSetup
    and ENDA_VehicleState.lastmodel == ENDA_VehicleState.model
    and ENDA_VehicleState.seat.last == ENDA_VehicleState.seat.current

  if not sameVehicleAndSeat then
    ENDA_VehicleState.layout = nil
    ENDA_VehicleState.lastmodel = ENDA_VehicleState.model
    ENDA_VehicleState.seat.last = ENDA_VehicleState.seat.current
    ENDA_VehicleState.class = GetVehicleClass(ENDA_VehicleState.id)
    ENDA_WeaponClipsetState.groupIndex = UpdateWeaponGroupIndex()
    ENDA_WeaponClipsetState.laststyle[ENDA_WeaponClipsetState.groupIndex] = ENDA_WeaponClipsetState.style[ENDA_WeaponClipsetState.groupIndex]
    SetDrivebyStyle(ENDA_WeaponClipsetState.groupIndex, ENDA_WeaponClipsetState.style[ENDA_WeaponClipsetState.groupIndex], true)
    SetVehicleFlag(ENDA_VehicleState.id, 168, true)
  elseif not ENDA_PlayerState.aimDisabled then
    SetPlayerCanDoDriveBy(ENDA_PlayerState.player, true)
  end

  ENDA_VehicleState.lastId = ENDA_VehicleState.id
  TriggerEvent("ENDA:EnteredVehicle", ENDA_VehicleState.id, ENDA_VehicleState.class, ENDA_VehicleState.model, ENDA_VehicleState.seat.current)

  if CONFIG.useCustomFirstPersonCam or CONFIG.useCustomThirdPersonCam then
    if ENDA_CameraState.view == nil then
      InitCustomCameras()
    end
  end

  if CONFIG.useCustomFirstPersonCam then
    if CONFIG.forceFirstPerson == 1 then
      if IsControlPressed(0, 25) then
        ENDA_PlayerState.aiming = true
        ActivateFpvAimCamera()
      end
    elseif CONFIG.forceFirstPerson == 2 then
      if ENDA_VehicleState.seat.current == -1 then
        ActivateFpvAimCamera()
      end
    elseif CONFIG.forceFirstPerson == 3 then
      ActivateFpvAimCamera()
    end
  end

  Wait(250)
  StartVehicleMonitorThread()
end

