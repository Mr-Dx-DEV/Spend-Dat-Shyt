function ApplyVehicleOverrideLayout(vehicleModel)
    local vehicleOverride = ENDA_VehicleOverrides[vehicleModel]
    if vehicleOverride == nil then
        ENDA_VehicleState.layout = ENDA_BuiltinVehicleLayouts[vehicleModel]
        return
    end

    if vehicleOverride.copy ~= nil then
        local copiedLayout = ENDA_BuiltinVehicleLayouts[vehicleOverride.copy]
        if copiedLayout == nil then
            return
        end

        ENDA_VehicleState.layout = copiedLayout

        if vehicleOverride.seats ~= nil then
            if ENDA_VehicleState.layout.seats == nil then
                ENDA_VehicleState.layout.seats = {}
            end

            for seatIndex = 1, #vehicleOverride.seats do
                local overrideSeatCode = vehicleOverride.seats[seatIndex]
                if overrideSeatCode ~= nil and overrideSeatCode ~= "COPY" then
                    ENDA_VehicleState.layout.seats[seatIndex] = overrideSeatCode
                end
            end
        end

        if vehicleOverride.hand ~= nil then
            ENDA_VehicleState.layout.hand = vehicleOverride.hand
        end
        return
    end

    if vehicleOverride.seats ~= nil then
        ENDA_VehicleState.layout = vehicleOverride

        for seatIndex = 1, #ENDA_VehicleState.layout.seats do
            if ENDA_VehicleState.layout.seats[seatIndex] == "COPY" then
                local builtinLayout = ENDA_BuiltinVehicleLayouts[vehicleModel]
                if builtinLayout ~= nil
                    and builtinLayout.seats ~= nil
                    and builtinLayout.seats[seatIndex] ~= nil then
                    ENDA_VehicleState.layout.seats[seatIndex] = builtinLayout.seats[seatIndex]

                    if ENDA_VehicleState.layout.hand == nil and builtinLayout.hand ~= nil then
                        ENDA_VehicleState.layout.hand = builtinLayout.hand
                    end
                end
            end
        end
        return
    end

    ENDA_VehicleState.layout = ENDA_BuiltinVehicleLayouts[vehicleModel]
end

function ResolveMissingSeatClipCode(seatIndex)
    if CONFIG.loadDefaultWhenClipsetNotFound and (seatIndex + 2) <= 4 then
        return "DEFAULT"
    end

    if CONFIG.allowVanillaAiming then
        return "GTA"
    end

    return "NONE"
end

function CreateDefaultVehicleLayout(defaultSeatCode)
    return {
        seats = { defaultSeatCode, defaultSeatCode, defaultSeatCode, defaultSeatCode },
    }
end

function ResolveSeatClipCode(vehicleModel, seatIndex)
    if not vehicleModel or seatIndex == nil then
        return nil
    end

    if not CONFIG.allowDriverDriveby and seatIndex == -1 then
        return "NONE"
    end

    if ENDA_VehicleState.layout == nil then
        ApplyVehicleOverrideLayout(vehicleModel)
    end

    local layoutSeatIndex = seatIndex + 2
    local layout = ENDA_VehicleState.layout

    if layout ~= nil and layout.seats ~= nil then
        local seatClipCode = layout.seats[layoutSeatIndex]
        if seatClipCode ~= nil then
            return seatClipCode
        end

        return ResolveMissingSeatClipCode(seatIndex)
    end

    if CONFIG.loadDefaultWhenClipsetNotFound then
        ENDA_VehicleState.layout = CreateDefaultVehicleLayout("DEFAULT")
        return "DEFAULT"
    end

    if CONFIG.allowVanillaAiming then
        ENDA_VehicleState.layout = CreateDefaultVehicleLayout("GTA")
        return "GTA"
    end

    return "NONE"
end

function ApplyDrivebyClipset(weaponGroupIndex, styleName, forceRefresh)
  if weaponGroupIndex == nil then
    weaponGroupIndex = ENDA_WeaponClipsetState.groupIndex
  end
  ENDA_PlayerState.aimDisabled = false
  if styleName == nil then
    styleName = ENDA_WeaponClipsetState.style[weaponGroupIndex]
  end
  if ENDA_VehicleState.seat.current == -1 then
    local weaponEntry = ENDA_DrivebyWeapons[ENDA_WeaponClipsetState.current]
    if weaponEntry ~= nil and weaponEntry[3] ~= nil and weaponEntry[3] == false then
      DisableDrivebyAiming()
      return
    end
  end
  if IsVanillaAimingAllowedForClass() or ((styleName == "DEFAULT" or styleName == "GTA") and weaponGroupIndex == 1) then
    RestoreVanillaOrDisableAiming(true)
    return
  end
  if IsVehicleAimingDisabledForClass() or IsJobDrivebyDisabled() then
    DisableDrivebyAiming()
    return
  end
  if styleName == "GTA" or styleName == "RESET" then
    RestoreVanillaOrDisableAiming()
    return
  end
  local allowCustomWithoutOverride = CONFIG.allowCustomAimingForAll and not CONFIG.disableAllVehicleAiming
  if not allowCustomWithoutOverride then
    if ENDA_VehicleOverrides[ENDA_VehicleState.model] == nil then
      if CONFIG.disableAllVehicleAiming then
        DisableDrivebyAiming()
        return
      elseif not CONFIG.allowCustomAimingForAll then
        RestoreVanillaOrDisableAiming()
        return
      end
    end
  end
  ENDA_ClipsetDictTemplate[6] = ResolveSeatClipCode(ENDA_VehicleState.model, ENDA_VehicleState.seat.current)
