      end
    end
  end
  step = ENDA_VehicleState.id
  if 0 == step then
    break
  end
  step = IsEntityDead
  argB = ENDA_PlayerState.id
  step = step(argB)
  if step then
    break
  end
  step = Citizen
  step = step.Wait
  argB = 1
  step(argB)
  monitorTick = monitorTick + 1
end
step = false
ENDA_VehicleMonitorRunning = step
step = CONFIG
step = step.useIntegratedAntiShuffle
if step then
  step = MonitorAntiShuffleSeat
  step()
end
step = CONFIG
step = step.useCustomFirstPersonCam
if step then
  step = DeactivateFpvCamera
  step()
end
step = CONFIG
step = step.useCustomThirdPersonCam
if step then
  step = DeactivateTpvCamera
  step()
end
ENDA_PlayerState.aimDisabled = false
ENDA_PlayerState.aimBlocked = false
step = false
ENDA_SuppressNotification = step
end


