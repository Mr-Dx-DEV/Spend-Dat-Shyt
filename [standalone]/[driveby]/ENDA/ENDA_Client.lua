function IsMouseInRect(centerX, centerY, width, height)
    local mouseX = GetDisabledControlNormal(0, 239)
    local mouseY = GetDisabledControlNormal(0, 240)

    ENDA_DevMouse.x = mouseX
    ENDA_DevMouse.y = mouseY

    if mouseX >= (centerX - (width / 2)) and mouseX <= (centerX + (width / 2)) then
        if mouseY > (centerY - (height / 2)) and mouseY < (centerY + (height / 2)) then
            return true
        end
    end

    return false
end

function DrawDevToolButton(centerX, centerY, width, height, textX, textY, label, idleAlpha, hoverAlpha)
    local isHovered = IsMouseInRect(centerX, centerY, width, height)

    if isHovered then
        DrawRect(centerX, centerY, width, height, 50, 50, 50, 150)
        DrawDevText(textX, textY, label, nil, nil, hoverAlpha)
    else
        DrawRect(centerX, centerY, width, height, 0, 0, 0, 150)
        DrawDevText(textX, textY, label, nil, nil, idleAlpha)
    end

    return isHovered and IsDisabledControlJustPressed(0, 24)
end

function AdjustSelectedSeatAxis(axisName, delta, minIndex, maxIndex, inputMode)
    local seatPed = ENDA_DevSeatPeds[ENDA_DevSelectedSeat]
    if seatPed == nil then
        return
    end

    local currentIndex = seatPed[axisName]
    if delta > 0 and currentIndex < maxIndex then
        seatPed[axisName] = currentIndex + 1
        RepositionDevSeatPed(ENDA_DevSelectedSeat)
        ENDA_DevInputMode = inputMode
    elseif delta < 0 and currentIndex > minIndex then
        seatPed[axisName] = currentIndex - 1
        RepositionDevSeatPed(ENDA_DevSelectedSeat)
        ENDA_DevInputMode = inputMode
    end
end

function ScrubSelectedSeatAnimTime(delta, fastStep)
    local seatPed = ENDA_DevSeatPeds[ENDA_DevSelectedSeat]
    if seatPed == nil or seatPed.anim == nil then
        return
    end

    local step = fastStep and 0.005 or 0.001
    local animTime = seatPed.anim[2]

    if delta < 0 and animTime > 0.02 then
        seatPed.anim[2] = animTime - step
    elseif delta > 0 and animTime < 0.98 then
        seatPed.anim[2] = animTime + step
    end
end

