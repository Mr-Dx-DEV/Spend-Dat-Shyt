            NormalizeAngle(ENDA_CameraState.rot.z - ENDA_VehicleState.rot.z),
            ENDA_TpvOffsetState.offCur[1],
            ENDA_TpvOffsetState.offCur[2],
            ENDA_TpvOffsetState.offCur[3]
        )
        AttachCamToPedBone(
            ENDA_CameraState.view.TPV_AIM,
            ENDA_PlayerState.id,
            40269,
            ENDA_CameraState.pos,
            true
        )
        SetCamRot(
            ENDA_CameraState.view.TPV_AIM,
            ENDA_CameraState.rot.x,
            ENDA_VehicleState.rot.y,
            ENDA_CameraState.rot.z,
            0
        )
