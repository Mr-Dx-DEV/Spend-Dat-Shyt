function DeleteAntiShufflePed()
    if ENDA_AntiShuffleState.ped == 0 or ENDA_AntiShuffleState.moving then
        return
    end

    SetEntityAsMissionEntity(ENDA_AntiShuffleState.ped, false, true)
    DeleteEntity(ENDA_AntiShuffleState.ped)

    if DoesEntityExist(ENDA_AntiShuffleState.ped) then
        Wait(15)
        DeleteAntiShufflePed()
        return
    end

    ENDA_AntiShuffleState.ped = 0
end

function SpawnAntiShufflePed(vehicleEntity)
    if ENDA_AntiShuffleState.ped ~= 0 then
        return
    end

    if vehicleEntity == nil then
        vehicleEntity = ENDA_VehicleState.id
    end

    NetworkRequestControlOfEntity(vehicleEntity)
    ENDA_AntiShuffleState.ped = ClonePed(ENDA_PlayerState.id, false, false, true)

    while not DoesEntityExist(ENDA_AntiShuffleState.ped) do
        Wait(1)
    end

    SetEntityVisible(ENDA_AntiShuffleState.ped, false, false)
    SetPedKeepTask(ENDA_AntiShuffleState.ped, true)
    SetBlockingOfNonTemporaryEvents(ENDA_AntiShuffleState.ped, true)
    SetEntityCollision(ENDA_AntiShuffleState.ped, false, true)
    FreezeEntityPosition(ENDA_AntiShuffleState.ped, true)

    if not IsVehicleSeatFree(vehicleEntity, -1, false) then
        for attemptIndex = 1, 15 do
            if IsVehicleSeatFree(vehicleEntity, -1, false) then
                break
            end
            Wait(100 * attemptIndex)
        end

        if not IsVehicleSeatFree(vehicleEntity, -1, true) then
            DeleteAntiShufflePed()
            return
        end
    end

    TaskEnterVehicle(ENDA_AntiShuffleState.ped, vehicleEntity, 3000, -1, 1.0, 16, 0)
    SetPedRelationshipGroupHash(ENDA_AntiShuffleState.ped, ENDA_AntiShuffleState.groupGood)

    Citizen.SetTimeout(2500, function()
        SetPedRelationshipGroupHash(ENDA_AntiShuffleState.ped, ENDA_AntiShuffleState.groupNull)
    end)
end

function MonitorAntiShuffleSeat()
    local currentSeat = ENDA_VehicleState.seat.current

    if currentSeat == 0 then
        if ENDA_AntiShuffleState.ped == 0 and not ENDA_AntiShuffleState.moving then
            if IsVehicleSeatFree(ENDA_VehicleState.id, -1, false) then
                NetworkRequestControlOfEntity(ENDA_VehicleState.id)
                SpawnAntiShufflePed(ENDA_VehicleState.id)
            end
        elseif ENDA_AntiShuffleState.ped ~= 0 and not ENDA_AntiShuffleState.moving then
            if not IsVehicleSeatFree(ENDA_VehicleState.id, -1) then
                if DoesEntityExist(ENDA_AntiShuffleState.ped) then
                    ENDA_AntiShuffleState.target = GetPedInVehicleSeat(ENDA_VehicleState.id, -1)
                    if ENDA_AntiShuffleState.target ~= 0
                        and ENDA_AntiShuffleState.target ~= ENDA_AntiShuffleState.ped then
                        DeleteAntiShufflePed()
                    end
                else
                    ENDA_AntiShuffleState.ped = 0
                end
            end
        end
    elseif ENDA_AntiShuffleState.ped ~= 0 then
        DeleteAntiShufflePed()
    end
end

