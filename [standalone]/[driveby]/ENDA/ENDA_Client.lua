        ENDA_CameraState.rot = GetEntityRotation(ENDA_VehicleState.id, 0)
        ENDA_InitialFlag = IsUsingKeyboard(1)

        if ENDA_LookState.firstTime then
            if ENDA_LookState.lookTimer == 0 then
                ENDA_LookState.lookTimer = ENDA_LookState.timeNow
            elseif ENDA_LookState.timeNow - ENDA_LookState.lookTimer > 500 then
                ENDA_LookState.firstTime = false
