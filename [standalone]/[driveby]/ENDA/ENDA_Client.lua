function FindNearestOffsetPreset(seatRole, offsetX, offsetY, offsetZ)
    local presetList = ENDA_DevOffsetPresets[seatRole]
    if presetList == nil then
        return false
    end

    local bestDistance = math.huge
    local bestCode = nil
    local bestCoords = { x = 8, y = 8, z = 3 }

    for _, preset in ipairs(presetList) do
        local deltaX = offsetX - preset.x
        local deltaY = offsetY - preset.y
        local deltaZ = offsetZ - preset.z
        local distance = (deltaX * deltaX) + (deltaY * deltaY) + (deltaZ * deltaZ)

        if distance < bestDistance then
            bestDistance = distance
            bestCode = preset.code
            bestCoords = { x = preset.x, y = preset.y, z = preset.z }
        end
    end

    return bestCode, bestCoords
end

