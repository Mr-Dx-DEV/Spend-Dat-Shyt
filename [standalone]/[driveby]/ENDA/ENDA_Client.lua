      if forceRefresh and ENDA_WeaponClipsetState.lastDict == ENDA_WeaponClipsetState.dict then
        SetDrivebyClipsetStateBag(ENDA_PlayerState.id, "DEFAULT")
        Wait(5)
      end
      SetDrivebyClipsetStateBag(ENDA_PlayerState.id, ENDA_WeaponClipsetState.dict)
      ENDA_WeaponClipsetState.lastDict = ENDA_WeaponClipsetState.dict
    end
  elseif CONFIG.loadDefaultWhenClipsetNotFound then
