local selectedLanguage = tostring(Config.Languange or Config.Language or "en")
if not Config.Translations[selectedLanguage] then
    selectedLanguage = "en"
end

Config.Language = selectedLanguage
Config.Languange = selectedLanguage
Config.LangT = Config.Translations[selectedLanguage] or Config.Translations.en

function Config.T(key, ...)
    if key == nil then
        return ""
    end

    local lang = Config.LangT or {}
    local fallback = Config.Translations and Config.Translations.en or {}
    local text = lang[key] or fallback[key] or tostring(key)

    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, text, ...)
        if ok then
            return formatted
        end
    end

    return text
end
