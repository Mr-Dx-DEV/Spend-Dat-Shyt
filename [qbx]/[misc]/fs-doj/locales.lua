-- Function to get locale string
function _L(key, ...)
    local lang = Config.Language or 'en'
    local locale = Locales[lang] or Locales['en']
    local str = locale[key] or key

    -- Handle string formatting
    if ... then
        return string.format(str, ...)
    end

    return str
end

