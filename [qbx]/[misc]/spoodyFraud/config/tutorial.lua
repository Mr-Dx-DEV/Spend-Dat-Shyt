**Welcome to spoodyFraud!**

Welcome. This laptop is your hub for every fraud operation: cloning cards, forging checks, swapping SIMs, and selling stolen data. Read this guide through once before you start, then follow the steps in order. Each job needs a specific device connected and the matching app open.

## Step 1 - Turn On the Proxy

Nothing will run until you're behind a proxy. Open the **Fraud Apps** folder and launch **proxy-net.exe**. Give it a moment to connect; once it finishes, you're routed through a secure tunnel and the other apps will unlock. If you skip this, every app will refuse to start.

## Step 2 - Opening an App

With the proxy running, double-click whichever app you want to use. Before you do, make sure the device that app relies on is plugged into the laptop. The list below shows exactly what each job needs.

## Materials & Devices

- **Card Cloning** - MSR (Magnetic Stripe Reader) + Blank Cards - card-cloner.exe
- **Check Fraud** - Printer + Check Paper - check-copy.exe
- **SIM Swapping** - Burner Phone + Empty SIM Cards - sim-swap.exe
- **Data Brokering** - USB Stick - data-broker.exe

## Step 3 - Cloning Cards

Connect your **MSR** to the laptop first, then open **card-cloner.exe** and wait for the console to confirm the device.

Once the app is up, close the laptop and swipe a blank card through the MSR. Reopen the laptop and hit **Clone** to start. When it finishes, your blank card becomes a cloned card that you can cash out at any ATM.

## Step 4 - Printing Checks

Connect your **Printer** first, then open **check-copy.exe** and wait for the console to confirm the device.

Once the app is up, close the laptop and load the check paper into the printer. Reopen the laptop and hit **Print Check** to start. When it finishes, you'll have a forged check ready to cash with a bank teller.

## Step 5 - Swapping SIMs

Connect your **Burner Phone** first, then open **sim-swap.exe** and wait for the console to confirm the device.

Once the app is up, close the laptop and insert a SIM card into the burner phone. Reopen the laptop and hit **Call Provider** to start the social-engineering call. After the call ends, the laptop reopens on its own and the SIM begins copying the transferred data. Once that completes, the swapped SIM is ready to sell.

## Step 6 - Brokering Data

This one only needs a **USB Stick** - no other device. Plug the USB into the laptop and open **data-broker.exe**.

Inside the app, download identity profiles one at a time until the USB is full. When it hits capacity, hit **Begin Transfer** to finalize everything onto the drive. Once the transfer's done, the loaded USB is ready to sell to your buyer.

## You're Set

That's every method. Keep the right device connected, keep the proxy running, and work one job at a time. Good luck.
